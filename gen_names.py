#!/usr/bin/env python3
"""Generate unames.h (Unicode character names for unimap) from Python's
unicodedata module.  Usage:  python3 gen_names.py > unames.h

Names that follow an algorithmic pattern (CJK ideographs, Tangut, ...) are
stored as compact ranges; Hangul syllables are built at runtime in C.
Newer Python = newer Unicode version = more names.
"""
import re
import sys
import unicodedata

C0 = ["NULL", "START OF HEADING", "START OF TEXT", "END OF TEXT",
      "END OF TRANSMISSION", "ENQUIRY", "ACKNOWLEDGE", "BELL", "BACKSPACE",
      "CHARACTER TABULATION", "LINE FEED", "LINE TABULATION", "FORM FEED",
      "CARRIAGE RETURN", "SHIFT OUT", "SHIFT IN", "DATA LINK ESCAPE",
      "DEVICE CONTROL ONE", "DEVICE CONTROL TWO", "DEVICE CONTROL THREE",
      "DEVICE CONTROL FOUR", "NEGATIVE ACKNOWLEDGE", "SYNCHRONOUS IDLE",
      "END OF TRANSMISSION BLOCK", "CANCEL", "END OF MEDIUM", "SUBSTITUTE",
      "ESCAPE", "INFORMATION SEPARATOR FOUR", "INFORMATION SEPARATOR THREE",
      "INFORMATION SEPARATOR TWO", "INFORMATION SEPARATOR ONE"]

pat = re.compile(r"^(.+)-([0-9A-F]{4,6})$")
names = []          # (cp, name)
ranges = []         # [lo, hi, prefix]

for cp in range(0x110000):
    if 0xAC00 <= cp <= 0xD7A3:      # Hangul syllables: algorithmic in C
        continue
    try:
        n = unicodedata.name(chr(cp))
    except ValueError:
        if cp < 0x20:
            n = C0[cp]
        elif cp == 0x7F:
            n = "DELETE"
        elif 0x80 <= cp < 0xA0:
            n = "<control>"
        else:
            continue
    m = pat.match(n)
    if m and int(m.group(2), 16) == cp:
        prefix = m.group(1)
        if ranges and ranges[-1][2] == prefix and ranges[-1][1] == cp - 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp, prefix])
        continue
    names.append((cp, n))

out = sys.stdout
out.write("/* Generated by gen_names.py - do not edit. */\n")
out.write('#define UNAMES_UNICODE "%s"\n' % unicodedata.unidata_version)
out.write("#define UN_COUNT %d\n\n" % len(names))

out.write("static const uint32_t un_cp[UN_COUNT] = {\n")
for i in range(0, len(names), 10):
    out.write(" " + ",".join("0x%X" % c for c, _ in names[i:i + 10]) + ",\n")
out.write("};\n\n")

out.write("static const struct { uint32_t lo, hi; const char *prefix; } un_ranges[] = {\n")
for lo, hi, p in ranges:
    out.write(' {0x%X, 0x%X, "%s"},\n' % (lo, hi, p))
out.write("};\n\n")

# Name pool in chunks < 4000 bytes (keeps -pedantic happy). Each chunk is a
# sequence of NUL-terminated names; the literal's own NUL ends the chunk.
out.write("static const char *const un_chunks[] = {\n")
chunk, size = [], 0
def flush():
    global chunk, size
    if chunk:
        out.write(" " + " ".join('"%s\\0"' % n for n in chunk) + ",\n")
    chunk, size = [], 0
for _, n in names:
    if size + len(n) + 1 > 3500:
        flush()
    chunk.append(n)
    size += len(n) + 1
flush()
out.write(" 0\n};\n")
