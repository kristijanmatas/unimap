/* Output buffer                                                       */
/* ------------------------------------------------------------------ */
static char *ob;
static size_t olen, ocap;

static void oadd(const char *s, size_t n)
{
    if (olen + n > ocap) {
        ocap = (olen + n) * 2 + 4096;
        ob = realloc(ob, ocap);
        if (!ob) _exit(1);
    }
    memcpy(ob + olen, s, n);
    olen += n;
}
static void oputs(const char *s) { oadd(s, strlen(s)); }
/* Switch to a theme style: reset, theme base colors, then the style. */
static void sty(const char *s) { oputs("\x1b[0m"); oputs(TH->base); oputs(s); }
#define RST() sty("")
static void ofmt(const char *fmt, ...)
{
    char tmp[1024];
    va_list ap;
    va_start(ap, fmt);
    int n = vsnprintf(tmp, sizeof tmp, fmt, ap);
    va_end(ap);
    if (n < 0) return;
    if ((size_t)n >= sizeof tmp) n = sizeof tmp - 1;
    oadd(tmp, (size_t)n);
}
static void wr(const char *s, size_t n)
{
    while (n > 0) {
        ssize_t r = write(1, s, n);
        if (r <= 0) return;
        s += r;
        n -= (size_t)r;
    }
}

