static const char **un_ptr;           /* un_ptr[i] -> name of un_cp[i] */

static void names_init(void)
{
    int n = 0;
    if (!HAVE_NAMES) return;
    un_ptr = malloc(sizeof *un_ptr * UN_COUNT);
    if (!un_ptr) { fputs("unimap: out of memory\n", stderr); exit(1); }
    for (int c = 0; un_chunks[c]; c++)
        for (const char *p = un_chunks[c]; *p && n < UN_COUNT; p += strlen(p) + 1)
            un_ptr[n++] = p;
    for (; n < UN_COUNT; n++) un_ptr[n] = "";
}

/* Returns the Unicode name of c, or NULL. tmp is scratch for built names. */
static const char *cp_name(uint32_t c, char *tmp, size_t sz)
{
    static const char *jl[] = {"G","GG","N","D","DD","R","M","B","BB","S","SS",
                               "","J","JJ","C","K","T","P","H"};
    static const char *jv[] = {"A","AE","YA","YAE","EO","E","YEO","YE","O","WA",
                               "WAE","OE","YO","U","WEO","WE","WI","YU","EU","YI","I"};
    static const char *jt[] = {"","G","GG","GS","N","NJ","NH","D","L","LG","LM",
                               "LB","LS","LT","LP","LH","M","B","BS","S","SS",
                               "NG","J","C","K","T","P","H"};
    int lo = 0, hi = UN_COUNT - 1;
    if (!HAVE_NAMES) return NULL;
    while (lo <= hi) {
        int m = (lo + hi) / 2;
        if (un_cp[m] == c) return un_ptr[m];
        if (un_cp[m] < c) lo = m + 1; else hi = m - 1;
    }
    if (c >= 0xAC00 && c <= 0xD7A3) {
        uint32_t s = c - 0xAC00;
        snprintf(tmp, sz, "HANGUL SYLLABLE %s%s%s", jl[s / 588], jv[(s % 588) / 28], jt[s % 28]);
        return tmp;
    }
    for (size_t i = 0; i < sizeof un_ranges / sizeof un_ranges[0]; i++)
        if (c >= un_ranges[i].lo && c <= un_ranges[i].hi) {
            snprintf(tmp, sz, "%s-%04X", un_ranges[i].prefix, c);
            return tmp;
        }
    if (c >= 0xD800 && c <= 0xDFFF) return "(surrogate)";
    if ((c >= 0xE000 && c <= 0xF8FF) || (c >= 0xF0000 && c <= 0x10FFFD)) return "(private use)";
    return NULL;
}

/* Decode exactly one UTF-8 sequence at s; returns its length or 0. */
static int utf8_dec(const char *s, uint32_t *o)
{
    const unsigned char *u = (const unsigned char *)s;
    int n, i;
    uint32_t v;
    if (u[0] == 0) return 0;
    if (u[0] < 0x80) { *o = u[0]; return 1; }
    if ((u[0] & 0xE0) == 0xC0) { n = 2; v = u[0] & 0x1F; }
    else if ((u[0] & 0xF0) == 0xE0) { n = 3; v = u[0] & 0x0F; }
    else if ((u[0] & 0xF8) == 0xF0) { n = 4; v = u[0] & 0x07; }
    else return 0;
    for (i = 1; i < n; i++) {
        if ((u[i] & 0xC0) != 0x80) return 0;
        v = (v << 6) | (u[i] & 0x3F);
    }
    *o = v;
    return n;
}

