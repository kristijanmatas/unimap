static void term_restore(void)
{
    static int done;
    if (done) return;
    done = 1;
    const char *s = "\x1b[0m\x1b[?1000l\x1b[?1006l\x1b[?7h\x1b[?25h\x1b[?1049l";
    wr(s, strlen(s));
    tcsetattr(0, TCSAFLUSH, &orig_tio);
}
static void on_signal(int sig)
{
    (void)sig;
    term_restore();
    _exit(1);
}

static int get_size(void)
{
    struct winsize ws;
    int w = 80, h = 24;
    if (ioctl(1, TIOCGWINSZ, &ws) == 0 && ws.ws_col > 0 && ws.ws_row > 0) {
        w = ws.ws_col;
        h = ws.ws_row;
    }
    if (w == W && h == H) return 0;
    W = w;
    H = h;
    return 1;
}

static int rows(void) { int r = H - 7; return r < 1 ? 1 : r; }

static void layout(void)
{
    lw  = W >= 100 ? 30 : 22;
    gx0 = lw + 2;
    gx  = gx0 + 8;
    cw  = (W - gx + 1 >= 64) ? 4 : 3;
}

/* ------------------------------------------------------------------ */
/* Navigation                                                          */
/* ------------------------------------------------------------------ */
static void fix_view(void)
{
    int nr = rows();
    uint32_t lo = blocks[blk].lo, hi = blocks[blk].hi;
    int row = (int)((cp - lo) / 16);
    int total = (int)((hi - lo) / 16) + 1;
    if (row < top) top = row;
    if (row >= top + nr) top = row - nr + 1;
    if (top > total - nr) top = total - nr;
    if (top < 0) top = 0;
    if (blk < btop) btop = blk;
    if (blk >= btop + nr) btop = blk - nr + 1;
    if (btop > NBLOCKS - nr) btop = NBLOCKS - nr;
    if (btop < 0) btop = 0;
}

static void set_block(int i)
{
    if (i < 0) i = 0;
    if (i >= NBLOCKS) i = NBLOCKS - 1;
    blk = i;
    cp = blocks[i].lo;
    top = 0;
    fix_view();
}

static void move_cp(long d)
{
    long n = (long)cp + d;
    if (n < (long)blocks[blk].lo) n = blocks[blk].lo;
    if (n > (long)blocks[blk].hi) n = blocks[blk].hi;
    cp = (uint32_t)n;
    fix_view();
}

static void move_v(int dir)
{
    uint32_t lo = blocks[blk].lo, hi = blocks[blk].hi;
    long n = (long)cp + dir * 16L;
    if (n < (long)lo) return;
    if (n > (long)hi) {
        if ((cp - lo) / 16 < (hi - lo) / 16) n = hi;
        else return;
    }
    cp = (uint32_t)n;
    fix_view();
}

static int goto_cp(uint32_t c)
{
    for (int i = 0; i < NBLOCKS; i++) {
        if (c >= blocks[i].lo && c <= blocks[i].hi) {
            blk = i;
            cp = c;
            top = 0;
            focus = 1;
            fix_view();
            return 1;
        }
    }
    return 0;
}

static int ci_contains(const char *h, const char *n)
{
    for (; *h; h++) {
        const char *a = h, *b = n;
        while (*a && *b && tolower((unsigned char)*a) == tolower((unsigned char)*b)) {
            a++;
            b++;
        }
        if (!*b) return 1;
    }
    return 0;
}

static void res_push(uint32_t v, int is_block)
{
    if (nres < MAXRES) { res[nres].v = v; res[nres].is_block = is_block; nres++; }
}

/* Run the query in inp[]: U+XXXX, a single character, or name words. */
static void run_search(void)
{
    char q[64], tok[6][64];
    int nt = 0;
    uint32_t c;
    int l;

    snprintf(q, sizeof q, "%s", inp);
    while (ninp > 0 && q[ninp - 1] == ' ') q[--ninp] = 0;   /* trim */
    char *p = q;
    while (*p == ' ') p++;
    if (!*p) return;

    /* U+XXXX */
    if ((p[0] == 'U' || p[0] == 'u') && p[1] == '+') {
        char *e;
        unsigned long v = strtoul(p + 2, &e, 16);
        if (e == p + 2 || *e || v > 0x10FFFF) setmsg("Bad code point \"%s\"", p);
        else if (!goto_cp((uint32_t)v)) setmsg("U+%04lX is not in any listed block", v);
        return;
    }
    /* one literal character */
    l = utf8_dec(p, &c);
    if (l > 0 && p[l] == 0) {
        if (!goto_cp(c)) setmsg("U+%04X is not in any listed block", c);
        return;
    }

    /* name words, all must match */
    for (char *w = strtok(p, " "); w && nt < 6; w = strtok(NULL, " "))
        snprintf(tok[nt++], sizeof tok[0], "%s", w);

    nres = 0;
    if (!scope_blk) {
        for (int i = 0; i < NBLOCKS; i++) {
            int ok = 1;
            for (int t = 0; t < nt && ok; t++) ok = ci_contains(blocks[i].name, tok[t]);
            if (ok) res_push((uint32_t)i, 1);
        }
    }
    uint32_t lo = scope_blk ? blocks[blk].lo : 0;
    uint32_t hi = scope_blk ? blocks[blk].hi : 0x10FFFF;
    for (int i = 0; i < UN_COUNT; i++) {
        if (un_cp[i] < lo) continue;
        if (un_cp[i] > hi) break;
        int ok = 1;
        for (int t = 0; t < nt && ok; t++) ok = ci_contains(un_ptr[i], tok[t]);
        if (ok) res_push(un_cp[i], 0);
    }

    snprintf(rquery, sizeof rquery, "%s", inp);
    if (nres == 0) {
        setmsg("No match for \"%s\"%s", inp, scope_blk ? " in this block" : "");
        return;
    }
    rsel = rtop = 0;
    mode = 3;
    if (nres >= MAXRES) setmsg("Showing the first %d matches - refine the search", MAXRES);
}

static void res_go(void)
{
    if (res[rsel].is_block) { set_block((int)res[rsel].v); focus = 1; }
    else goto_cp(res[rsel].v);
    mode = 0;
}

/* ------------------------------------------------------------------ */
/* Text buffer + clipboard                                             */
/* ------------------------------------------------------------------ */
static size_t buf_utf8(char *out)
{
    size_t n = 0;
    for (int i = 0; i < nbuf; i++) n += (size_t)u8enc(buf[i], out + n);
    out[n] = 0;
    return n;
}

static void add_char(void)
{
    if (!safe_cp(cp)) { setmsg("U+%04X can't be added to the text", cp); return; }
    if (nbuf >= MAXBUF) { setmsg("Text buffer full"); return; }
    buf[nbuf++] = cp;
}

static void b64(const unsigned char *s, size_t n, char *o)
{
    static const char t[] =
        "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    size_t j = 0;
    for (size_t i = 0; i < n; i += 3) {
        unsigned v = (unsigned)s[i] << 16;
        if (i + 1 < n) v |= (unsigned)s[i + 1] << 8;
        if (i + 2 < n) v |= s[i + 2];
        o[j++] = t[(v >> 18) & 63];
        o[j++] = t[(v >> 12) & 63];
        o[j++] = (i + 1 < n) ? t[(v >> 6) & 63] : '=';
        o[j++] = (i + 2 < n) ? t[v & 63] : '=';
    }
    o[j] = 0;
}

static void do_copy(void)
{
    char text[MAXBUF * 4 + 8];
    size_t n;
    int count;
    if (nbuf > 0) {
        n = buf_utf8(text);
        count = nbuf;
    } else if (safe_cp(cp)) {
        n = (size_t)u8enc(cp, text);
        text[n] = 0;
        count = 1;
    } else {
        setmsg("Nothing to copy");
        return;
    }

    /* 1) OSC 52 (works in most modern terminals, also over SSH) */
    char *e = malloc(((n + 2) / 3) * 4 + 1);
    if (e) {
        b64((unsigned char *)text, n, e);
        wr("\x1b]52;c;", 7);
        wr(e, strlen(e));
        wr("\x07", 1);
        free(e);
    }

    /* 2) external helpers */
    static const char *cmds[] = {
        "wl-copy >/dev/null 2>&1",
        "xclip -selection clipboard >/dev/null 2>&1",
        "xsel -ib >/dev/null 2>&1",
        "pbcopy >/dev/null 2>&1",
        NULL
    };
    const char *used = NULL;
    for (int i = 0; cmds[i]; i++) {
        FILE *f = popen(cmds[i], "w");
        if (!f) continue;
        fwrite(text, 1, n, f);
        if (pclose(f) == 0) {
            used = cmds[i];
            break;
        }
    }
    if (used) {
        char name[16];
        snprintf(name, sizeof name, "%.*s", (int)strcspn(used, " "), used);
        setmsg("Copied %d char%s (%s + OSC 52)", count, count == 1 ? "" : "s", name);
    } else {
        setmsg("Copied %d char%s via OSC 52 (no wl-copy/xclip/xsel found)",
               count, count == 1 ? "" : "s");
    }
}

/* ------------------------------------------------------------------ */
/* Input                                                               */
/* ------------------------------------------------------------------ */
static int rd(void)
{
    unsigned char c;
    return read(0, &c, 1) == 1 ? c : -1;
}

static int read_key(void)
{
    int c = rd();
    if (c < 0) return 0;
    if (c != 27) return c;
    int c1 = rd();
    if (c1 < 0) return 27;
    if (c1 == '[') {
        int c2 = rd();
        if (c2 < 0) return 0;
        if (c2 == '<') {                       /* SGR mouse */
            int v[3] = {0, 0, 0}, i = 0, ch;
            while ((ch = rd()) >= 0) {
                if (ch >= '0' && ch <= '9') v[i] = v[i] * 10 + (ch - '0');
                else if (ch == ';') { if (i < 2) i++; }
                else {
                    if (ch == 'M') { mb = v[0]; mx = v[1]; my = v[2]; return KEY_MOUSE; }
                    return 0;
                }
            }
            return 0;
        }
        switch (c2) {
        case 'A': return KEY_UP;
        case 'B': return KEY_DOWN;
        case 'C': return KEY_RIGHT;
        case 'D': return KEY_LEFT;
        case 'H': return KEY_HOME;
        case 'F': return KEY_END;
        case 'Z': return KEY_BTAB;
        }
        if (c2 >= '0' && c2 <= '9') {
            int n = c2 - '0', ch;
            while ((ch = rd()) >= '0' && ch <= '9') n = n * 10 + (ch - '0');
            switch (n) {
            case 1: case 7: return KEY_HOME;
            case 4: case 8: return KEY_END;
            case 5: return KEY_PGUP;
            case 6: return KEY_PGDN;
            case 3: return KEY_DEL;
            }
        }
        return 0;
    }
    if (c1 == 'O') {
        int c2 = rd();
        switch (c2) {
        case 'A': return KEY_UP;
        case 'B': return KEY_DOWN;
        case 'C': return KEY_RIGHT;
        case 'D': return KEY_LEFT;
        case 'H': return KEY_HOME;
        case 'F': return KEY_END;
        }
    }
    return 0;
}

static void handle_mouse(void)
{
    static long last_t;
    static uint32_t last_cp = 0xFFFFFFFF;
    int nr = rows();

    if (mb == 64 || mb == 65) {                /* wheel */
        int dir = (mb == 64) ? -1 : 1;
        if (mx <= lw) set_block(blk + dir);
        else { focus = 1; move_cp(dir * 48L); }
        return;
    }
    if (mb != 0) return;                       /* left button only */
    if (my < 3 || my > 2 + nr) return;

    if (mx <= lw) {
        int idx = btop + (my - 3);
        if (idx < NBLOCKS) { set_block(idx); focus = 0; }
    } else if (mx >= gx && mx < gx + 16 * cw) {
        int col = (mx - gx) / cw;
        int row = top + (my - 3);
        uint32_t c = blocks[blk].lo + (uint32_t)row * 16 + (uint32_t)col;
        if (c > blocks[blk].hi) return;
        long t = now_ms();
        focus = 1;
        cp = c;
        fix_view();
        if (c == last_cp && t - last_t < 400) { add_char(); last_cp = 0xFFFFFFFF; }
        else { last_cp = c; last_t = t; }
    }
}

static void prompt_key(int k)
{
    if (k == 27) { mode = 0; return; }
    if (k == '\r' || k == '\n') {
        int m = mode;
        mode = 0;
        if (ninp > 0) {
            if (m == 1) {
                unsigned long v = strtoul(inp, NULL, 16);
                if (v > 0x10FFFF) setmsg("Code point out of range");
                else if (!goto_cp((uint32_t)v))
                    setmsg("U+%04lX is not in any listed block", v);
            } else {
                run_search();                  /* may switch to mode 3 */
            }
        }
        return;
    }
    if (k == '\t' && mode == 2) { scope_blk ^= 1; return; }
    if (k == 127 || k == 8) {
        while (ninp > 0 && ((unsigned char)inp[ninp - 1] & 0xC0) == 0x80) ninp--;
        if (ninp) ninp--;
        inp[ninp] = 0;
        return;
    }
    if (mode == 1) {
        if (k < 128 && isxdigit(k) && ninp < 6) { inp[ninp++] = (char)k; inp[ninp] = 0; }
    } else if (((k >= 32 && k < 127) || (k >= 128 && k < 256)) && ninp < 60) {
        inp[ninp++] = (char)k;               /* UTF-8 bytes arrive one by one */
        inp[ninp] = 0;
    }
}

static void results_key(int k)
{
    int nr = rows();
    switch (k) {
    case 27: case 'q': mode = 0; return;
    case KEY_UP: case 'k': if (rsel > 0) rsel--; break;
    case KEY_DOWN: case 'j': if (rsel < nres - 1) rsel++; break;
    case KEY_PGUP: rsel -= nr; break;
    case KEY_PGDN: rsel += nr; break;
    case KEY_HOME: rsel = 0; break;
    case KEY_END: rsel = nres - 1; break;
    case '\r': case '\n': res_go(); return;
    case ' ':
        if (!res[rsel].is_block) {
            uint32_t save = cp;
            cp = res[rsel].v;
            add_char();
            cp = save;
        }
        return;
    case '/': mode = 2; scope_blk = 0; ninp = 0; inp[0] = 0; return;
    case KEY_MOUSE:
        if (mb == 64) rsel -= 3;
        else if (mb == 65) rsel += 3;
        else if (mb == 0 && my >= 3 && my <= 2 + nr && mx >= gx0) {
            int i = rtop + (my - 3);
            if (i < nres) { if (i == rsel) { res_go(); return; } rsel = i; }
        }
        break;
    default: return;
    }
    if (rsel < 0) rsel = 0;
    if (rsel > nres - 1) rsel = nres - 1;
    if (rsel < rtop) rtop = rsel;
    if (rsel >= rtop + nr) rtop = rsel - nr + 1;
    if (rtop < 0) rtop = 0;
}

static void handle_key(int k)
{
    int nr = rows();
    msg[0] = 0;
    if (mode == 3) { results_key(k); return; }
    if (mode) { prompt_key(k); return; }

    switch (k) {
    case 'q': case 3: running = 0; return;
    case '\t': case KEY_BTAB: focus ^= 1; return;
    case KEY_UP: case 'k':
        if (focus == 0) set_block(blk - 1); else move_v(-1);
        return;
    case KEY_DOWN: case 'j':
        if (focus == 0) set_block(blk + 1); else move_v(1);
        return;
    case KEY_LEFT: case 'h':
        if (focus == 1) { if (cp > blocks[blk].lo) move_cp(-1); else focus = 0; }
        return;
    case KEY_RIGHT: case 'l':
        if (focus == 0) focus = 1; else move_cp(1);
        return;
    case KEY_PGUP:
        if (focus == 0) set_block(blk - nr); else move_cp(-16L * nr);
        return;
    case KEY_PGDN:
        if (focus == 0) set_block(blk + nr); else move_cp(16L * nr);
        return;
    case KEY_HOME:
        if (focus == 0) set_block(0);
        else { cp = blocks[blk].lo + ((cp - blocks[blk].lo) & ~15u); fix_view(); }
        return;
    case KEY_END:
        if (focus == 0) set_block(NBLOCKS - 1);
        else {
            uint32_t e = blocks[blk].lo + ((cp - blocks[blk].lo) & ~15u) + 15;
            cp = e > blocks[blk].hi ? blocks[blk].hi : e;
            fix_view();
        }
        return;
    case 'n': case ']': set_block(blk + 1); return;
    case 'p': case '[': set_block(blk - 1); return;
    case '\r': case '\n':
        if (focus == 0) focus = 1; else add_char();
        return;
    case ' ': add_char(); return;
    case 127: case 8: case KEY_DEL: if (nbuf) nbuf--; return;
    case 'x': nbuf = 0; return;
    case 'c': case 'y': do_copy(); return;
    case 't': case 'T':
        theme = (theme + (k == 't' ? 1 : NTHEMES - 1)) % NTHEMES;
        setmsg("Theme: %s  (start with -t %s or UNIMAP_THEME=%s to keep it)",
               TH->name, TH->name, TH->name);
        return;
    case 'g': mode = 1; ninp = 0; inp[0] = 0; return;
    case '/': mode = 2; scope_blk = 0; ninp = 0; inp[0] = 0; return;
    case KEY_MOUSE: handle_mouse(); return;
    }
}

/* ------------------------------------------------------------------ */
/* Drawing                                                             */
/* ------------------------------------------------------------------ */
static void draw(void)
{
    int nr = rows(), i;
    const Block *b = &blocks[blk];
    char g[8], tmp[256];
    int w;

    layout();
    fix_view();
    olen = 0;
    oputs("\x1b[?25l");
    RST();
    oputs("\x1b[H\x1b[2J");

    /* title bar */
    snprintf(tmp, sizeof tmp, " unimap  -  Unicode character map   (names: %s%s)   theme: %s",
             HAVE_NAMES ? "Unicode " : "", UNAMES_UNICODE, TH->name);
    oputs("\x1b[1;1H");
    sty(TH->bar);
    ofmt("%-*.*s", W, W, tmp);
    RST();

    /* block list */
    snprintf(tmp, sizeof tmp, " Blocks %d/%d", blk + 1, NBLOCKS);
    oputs("\x1b[2;1H");
    sty(TH->head);
    ofmt("%-*.*s", lw, lw, tmp);
    RST();
    for (i = 0; i < nr; i++) {
        int idx = btop + i, y = 3 + i;
        ofmt("\x1b[%d;1H", y);
        if (idx < NBLOCKS) {
            if (idx == blk) sty(focus == 0 ? TH->sel : TH->sel2);
            ofmt(" %-*.*s", lw - 1, lw - 1, blocks[idx].name);
            RST();
        } else {
            ofmt("%*s", lw, "");
        }
    }
    sty(TH->dim);
    for (i = 0; i <= nr; i++)
        ofmt("\x1b[%d;%dH\xE2\x94\x82", 2 + i, lw + 1);
    RST();

    if (mode == 3) {
        /* search results */
        int rw = W - gx0 + 1;
        snprintf(tmp, sizeof tmp, " %d result%s for \"%s\"%s", nres, nres == 1 ? "" : "s",
                 rquery, scope_blk ? "  (this block)" : "");
        ofmt("\x1b[2;%dH", gx0);
        sty(TH->head);
        ofmt("%-*.*s", rw, rw, tmp);
        RST();
        for (i = 0; i < nr; i++) {
            int idx = rtop + i, y = 3 + i;
            if (idx >= nres) break;
            ofmt("\x1b[%d;%dH", y, gx0);
            if (idx == rsel) sty(TH->sel);
            ofmt("%*s", rw, "");
            if (res[idx].is_block) {
                const Block *rb = &blocks[res[idx].v];
                ofmt("\x1b[%d;%dH U+%04X..U+%04X", y, gx0, rb->lo, rb->hi);
                ofmt("\x1b[%d;%dH[block] %.*s", y, gx0 + 20, rw - 28 > 0 ? rw - 28 : 1, rb->name);
            } else {
                uint32_t c = res[idx].v;
                const char *nm = cp_name(c, tmp, sizeof tmp);
                int t = glyph(c, g, &w);
                ofmt("\x1b[%d;%dH U+%-6X", y, gx0, c);
                ofmt("\x1b[%d;%dH%s%s", y, gx0 + 10, w == 0 ? "\xE2\x97\x8C" : "", t ? g : "\xC2\xB7");
                ofmt("\x1b[%d;%dH%.*s", y, gx0 + 14, rw - 14 > 0 ? rw - 14 : 1, nm ? nm : "");
            }
            RST();
        }
    } else {
    /* column header */
    sty(TH->head);
    for (i = 0; i < 16; i++) ofmt("\x1b[2;%dH%X", gx + i * cw + 1, i);
    RST();

    /* grid */
    for (i = 0; i < nr; i++) {
        uint32_t rs = b->lo + (uint32_t)(top + i) * 16;
        int y = 3 + i;
        if (rs > b->hi) break;
        snprintf(tmp, sizeof tmp, "U+%03Xx", rs >> 4);
        ofmt("\x1b[%d;%dH", y, gx0);
        sty(TH->dim);
        ofmt("%-7s", tmp);
        RST();
        for (int col = 0; col < 16; col++) {
            uint32_t c = rs + (uint32_t)col;
            if (c > b->hi) break;
            int t = glyph(c, g, &w);
            int sel = (c == cp);
            ofmt("\x1b[%d;%dH", y, gx + col * cw);
            if (sel) sty(focus == 1 ? TH->sel : TH->sel2);
            else if (t != 1) sty(TH->dim);
            oputs(" ");
            int vis = w;
            if (w == 0) { oputs("\xE2\x97\x8C"); vis = 1; }   /* dotted circle */
            oputs(g);
            ofmt("%*s", cw - 1 - vis, "");
            if (sel || t != 1) RST();
        }
    }

    }   /* grid vs results */

    /* info lines */
    {
        char u8[8], nbuf2[96];
        int n = u8enc(cp, u8), t = glyph(cp, g, &w);
        char bytes[40] = "";
        const char *nm = cp_name(cp, nbuf2, sizeof nbuf2);
        for (i = 0; i < n; i++) {
            char one[5];
            snprintf(one, sizeof one, "%02X ", (unsigned char)u8[i]);
            strcat(bytes, one);
        }
        ofmt("\x1b[%d;1H\x1b[K", H - 4);
        sty(TH->accent);
        ofmt(" U+%04X", cp);
        RST();
        ofmt("  %s%s   ", w == 0 ? "\xE2\x97\x8C" : "", t == 1 ? g : "-");
        sty(TH->accent);
        oputs(nm ? nm : HAVE_NAMES ? "(unassigned)" : "(names not built in)");
        RST();
        ofmt("\x1b[%d;1H\x1b[K dec %u   UTF-8: %s  Block: %s   [%s]",
             H - 3, cp, bytes, b->name, classify(cp));
    }

    /* text buffer / prompt */
    ofmt("\x1b[%d;1H\x1b[K", H - 2);
    sty(TH->head);
    if (mode == 1) {
        oputs(" Go to U+");
        RST();
        ofmt("%s_", inp);
    } else if (mode == 2) {
        ofmt(" Search (%s): ", scope_blk ? "this block" : "all");
        RST();
        ofmt("%s_", inp);
    } else {
        char out[MAXBUF * 4 + 8];
        int maxc = W - 10;
        int start = nbuf > maxc ? nbuf - maxc : 0;
        size_t n = 0;
        for (i = start; i < nbuf; i++) n += (size_t)u8enc(buf[i], out + n);
        out[n] = 0;
        oputs(" Text:");
        RST();
        ofmt(" %s", out);
        sty(TH->dim);
        oputs("|");
        RST();
    }

    /* message + help */
    ofmt("\x1b[%d;1H\x1b[K", H - 1);
    sty(TH->msg);
    ofmt(" %s", msg);
    RST();
    ofmt("\x1b[%d;1H", H);
    sty(TH->bar);
    if (mode == 1)
        ofmt("%-*.*s", W, W, " Hex code point   Enter = go   Esc = cancel");
    else if (mode == 2)
        ofmt("%-*.*s", W, W,
             " Name words, one char, or U+XXXX   Tab = scope (all / this block)"
             "   Enter = search   Esc = cancel");
    else if (mode == 3)
        ofmt("%-*.*s", W, W,
             " Up/Down select   Enter go   Space add to text   / new search   Esc close");
    else
        ofmt("%-*.*s", W, W,
             " Tab pane  arrows/hjkl move  Enter add  c copy  Bksp del  x clear"
             "  g goto  / search  n/p block  t theme  q quit");
    RST();

    wr(ob, olen);
}

